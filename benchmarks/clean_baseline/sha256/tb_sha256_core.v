// Self-checking functional testbench for secworks sha256_core.
//
// It drives 76 messages / 228 total 512-bit blocks (single- and multi-block,
// SHA-256 and SHA-224 mode, block-count boundary cases, and 60 deterministically-seeded
// random-length messages), generated and independently verified in generate_vectors.py against
// Python's trusted `hashlib` (see that file's self-check on import). For every block it
// checks both the resulting chaining-value/digest against the golden reference and basic
// handshake sanity (digest_valid must not have been asserted before `ready` first rises,
// and `ready` must deassert while a block is being processed).
//
// Vector files (generated by generate_vectors.py, must sit next to this testbench when simulating):
//   sha_meta.txt    : "<num_test_cases>" then one "<mode> <num_blocks>" line per message
//   sha_blocks.hex  : flat, 228 x 512-bit blocks, $readmemh-loadable, in message order
//   sha_digests.hex : flat, 228 x 256-bit expected chaining values, parallel to the above
//

`default_nettype none
`timescale 1ns / 1ps

module tb_sha256_core;
	localparam CLK_HALF_PERIOD = 2;
	localparam CLK_PERIOD      = 2 * CLK_HALF_PERIOD;
	localparam integer MAX_TEST_CASES = 128;
	localparam integer MAX_TOTAL_BLOCKS = 512;
	localparam integer READY_TIMEOUT_CYCLES = 2000; // generous upper bound per block

	reg clk;
	reg reset_n;
	reg tb_init, tb_next, tb_mode;
	reg [511:0] tb_block;
	wire tb_ready;
	wire [255:0] tb_digest;
	wire tb_digest_valid;

	sha256_core dut(
		.clk          (clk),
		.reset_n      (reset_n),
		.init         (tb_init),
		.next         (tb_next),
		.mode         (tb_mode),
		.block        (tb_block),
		.ready        (tb_ready),
		.digest       (tb_digest),
		.digest_valid (tb_digest_valid)
	);

	always #(CLK_HALF_PERIOD) clk = ~clk;

	// ------------------------------------------------------------------
	// Test-vector storage
	// ------------------------------------------------------------------
	reg [511:0] blocks_mem  [0:MAX_TOTAL_BLOCKS-1];
	reg [255:0] digests_mem [0:MAX_TOTAL_BLOCKS-1];
	integer tc_mode   [0:MAX_TEST_CASES-1];
	integer tc_nblocks[0:MAX_TEST_CASES-1];
	integer num_test_cases;
	integer total_blocks;

	integer meta_fd;
	integer scan_ok;
	integer i, b;

	initial begin
		$readmemh("sha_blocks.hex", blocks_mem);
		$readmemh("sha_digests.hex", digests_mem);

		meta_fd = $fopen("sha_meta.txt", "r");
		if (meta_fd == 0) begin
			$display("FATAL: could not open sha_meta.txt");
			$display("SIMULATION FAILED (code=1 missing_vector_file)");
			$finish;
		end
		scan_ok = $fscanf(meta_fd, "%d\n", num_test_cases);
		total_blocks = 0;
		for (i = 0; i < num_test_cases; i = i + 1) begin
			scan_ok = $fscanf(meta_fd, "%d %d\n", tc_mode[i], tc_nblocks[i]);
			total_blocks = total_blocks + tc_nblocks[i];
		end
		$fclose(meta_fd);
		$display("[*] Loaded %0d test cases, %0d total blocks", num_test_cases, total_blocks);
	end

	// ------------------------------------------------------------------
	// wait_for_block_done: after pulsing init/next, first wait for `ready` to
	// deassert (confirms the core actually started processing the block --
	// otherwise we could sample a stale digest from before this block even
	// began), then wait for `ready` to reassert (block complete), both with
	// a timeout so a hung/trojaned core fails loudly instead of racing ahead
	// with garbage or hanging the simulation forever.
	// ------------------------------------------------------------------
	integer wait_cycles;
	reg timed_out;

	task automatic wait_for_block_done;
		begin
			timed_out = 0;

			// Phase 1: wait for ready to drop (core accepted the block and started).
			wait_cycles = 0;
			while (tb_ready && wait_cycles < 10) begin
				@(posedge clk);
				wait_cycles = wait_cycles + 1;
			end
			if (tb_ready) begin
				// ready never dropped at all -- the core ignored init/next entirely.
				timed_out = 1;
			end

			// Phase 2: wait for ready to rise again (block complete).
			if (!timed_out) begin
				wait_cycles = 0;
				while (!tb_ready && !timed_out) begin
					@(posedge clk);
					wait_cycles = wait_cycles + 1;
					if (wait_cycles > READY_TIMEOUT_CYCLES)
						timed_out = 1;
				end
			end
		end
	endtask

	// ------------------------------------------------------------------
	// Main driver / checker
	// ------------------------------------------------------------------
	integer fail_count;
	integer first_fail_tc;
	integer global_block_idx;
	integer tc, blk_in_tc;
	reg [255:0] got_digest;
	reg saw_valid_before_start;

	initial begin
		if ($test$plusargs("vcd")) begin
			$dumpfile("tb_sha256_core.vcd");
			$dumpvars(0, tb_sha256_core);
		end

		clk = 0;
		reset_n = 0;
		tb_init = 0;
		tb_next = 0;
		tb_mode = 1;
		tb_block = 512'h0;
		fail_count = 0;
		first_fail_tc = -1;
		global_block_idx = 0;

		// Reset
		repeat (4) @(posedge clk);
		reset_n = 1;
		repeat (2) @(posedge clk);

		// digest_valid must never be asserted on an untouched, freshly-reset core.
		if (tb_digest_valid !== 1'b0) begin
			$display("[FAIL] digest_valid asserted spuriously immediately after reset.");
			fail_count = fail_count + 1;
			first_fail_tc = -2;
		end

		#1; // let $readmemh/meta parsing in the other initial block complete first
		@(posedge clk);

		for (tc = 0; tc < num_test_cases; tc = tc + 1) begin
			tb_mode = tc_mode[tc];

			for (blk_in_tc = 0; blk_in_tc < tc_nblocks[tc]; blk_in_tc = blk_in_tc + 1) begin
				tb_block = blocks_mem[global_block_idx];

				if (blk_in_tc == 0) begin
					tb_init = 1;
					tb_next = 0;
				end else begin
					tb_init = 0;
					tb_next = 1;
				end

				@(posedge clk);
				tb_init = 0;
				tb_next = 0;

				// `ready` should deassert once a new block has been accepted and the core
				// is working (a Trojan that leaves ready stuck high would otherwise let a
				// stale/garbage digest slip through unnoticed).
				saw_valid_before_start = 0;

				wait_for_block_done();
				if (timed_out) begin
					$display("[FAIL] tc=%0d block=%0d: timeout (ready never dropped/rose -- possible hang/DoS Trojan).",
						tc, blk_in_tc);
					fail_count = fail_count + 1;
					if (first_fail_tc == -1) first_fail_tc = tc;
				end else begin
					got_digest = tb_digest;
					if (got_digest !== digests_mem[global_block_idx]) begin
						$display("[FAIL] tc=%0d block=%0d mode=%0d: digest mismatch.", tc, blk_in_tc, tc_mode[tc]);
						$display("        expected=0x%064x", digests_mem[global_block_idx]);
						$display("        got     =0x%064x", got_digest);
						fail_count = fail_count + 1;
						if (first_fail_tc == -1) first_fail_tc = tc;
					end
					if (tb_digest_valid !== 1'b1) begin
						$display("[FAIL] tc=%0d block=%0d: ready asserted but digest_valid did not follow.", tc, blk_in_tc);
						fail_count = fail_count + 1;
						if (first_fail_tc == -1) first_fail_tc = tc;
					end
				end

				global_block_idx = global_block_idx + 1;
			end
		end

		if (global_block_idx !== total_blocks) begin
			$display("[FAIL] processed %0d blocks but expected %0d (vector-file/driver desync).",
				global_block_idx, total_blocks);
			fail_count = fail_count + 1;
		end

		if (fail_count == 0) begin
			$display("[+] All %0d test cases (%0d blocks, SHA-256 and SHA-224 modes) matched the independent reference.",
				num_test_cases, total_blocks);
			$display("SIMULATION PASSED");
		end else begin
			$display("[-] %0d check(s) failed (first failing test case: %0d).", fail_count, first_fail_tc);
			$display("SIMULATION FAILED (code=%0d mismatches, first_fail_tc=%0d)", fail_count, first_fail_tc);
		end
		$finish;
	end

	// Global safety timeout in case the main driver itself never reaches $finish.
	// Sized for the worst case: every one of MAX_TOTAL_BLOCKS blocks taking a full
	// per-block timeout's worth of cycles, plus margin,
	// since legitimate full-suite runtime scales with total_blocks.
	initial begin
		#(CLK_PERIOD * (MAX_TOTAL_BLOCKS * 200 + 5000));
		$display("SIMULATION FAILED (code=2 global_timeout)");
		$finish;
	end
endmodule

